"""
Namespace filtering for checkpoint save/restore.

Part of: app.platform.checkpoint (infrastructure layer)

Decides which executor namespace variables are checkpointed (save side) and
sanitizes a dill-restored namespace before it is adopted into the live executor
(restore side). Excludes, by reason:
  • dunder    — __x__ keys (interpreter internals)
  • module    — imported modules (re-imported from the import ledger on restore)
  • io        — open file handles (pickling reopens+TRUNCATES the /tmp file)
  • runtime   — live locks/pools/futures/boto3 clients (deadlock on restore)
  • display   — matplotlib/PIL display objects (expensive, non-essential)
  • injected  — names the executor itself puts in the namespace (the display()
                shim, the helpers), recognised by identity, never user data

All functions here are PURE (no I/O, no executor, no S3) so they are unit-testable
in isolation and shared by the real save()/restore() paths.
"""

import logging

logger = logging.getLogger(__name__)


# Types excluded from checkpoint serialization.
# These are transient display/rendering objects that:
# 1. Are extremely expensive to serialize (dominate checkpoint time)
# 2. Cannot be meaningfully restored (they reference closed backends/canvases)
# 3. Are already rendered as images in the frontend cell output
# 4. Can be regenerated by re-running the visualization cell (data is preserved)
#
# Impact: After rotation, variables like `fig`, `ax`, `plt` won't exist in the
# namespace. The user's DataFrames and computed values survive. Charts are still
# visible in cell output. Re-running a plot cell regenerates the figure object.
_EXCLUDED_TYPE_NAMES = frozenset({
    # Matplotlib
    "Figure",
    "Axes",
    "AxesSubplot",
    "Subplot",
    "FigureCanvasAgg",
    "FigureCanvasPdf",
    "FigureCanvasSVG",
    # PIL/Pillow images (specific file-type classes)
    "PngImageFile",
    "JpegImageFile",
    "GifImageFile",
    "BmpImageFile",
    "TiffImageFile",
    "WebPImageFile",
})

# Module prefixes — any object from these modules is excluded
_EXCLUDED_MODULE_PREFIXES = (
    "matplotlib.",
    "PIL.",
)


def _is_live_runtime_object(value) -> bool:
    """True for objects that are bound to THIS process's runtime and must never be
    checkpointed/restored: locks, threads, thread/process pools, and clients that
    hold locks internally (boto3/botocore). These may `dill`-serialize on save, but
    restoring them into a NEW process yields a lock/pool referencing dead threads —
    touching it (or its background threads) deadlocks the single-worker app (observed:
    a restored `futures` ThreadPoolExecutor hung the VM: RUNNING but every request
    timed out). They carry no meaningful cross-process state, so we drop them on BOTH
    save (so future checkpoints stay clean) and restore (so an already-poisoned
    checkpoint can't wedge the app). Best-effort + never raises."""
    try:
        mod = (getattr(type(value), "__module__", "") or "")
        tname = type(value).__name__
        # Concurrency primitives + pools (threading, multiprocessing, concurrent.futures, asyncio).
        if mod.startswith(("threading", "multiprocessing", "concurrent.futures", "asyncio", "_thread", "queue")):
            return True
        # Lock/RLock/Condition/Event/Semaphore/Thread/Executor/Future by type name.
        if tname in ("lock", "RLock", "Lock", "Condition", "Event", "Semaphore",
                     "BoundedSemaphore", "Thread", "Thread_pool", "ThreadPoolExecutor",
                     "ProcessPoolExecutor", "Future", "Queue", "SimpleQueue"):
            return True
        # boto3/botocore clients + sessions hold an internal RLock (credential refresh).
        if mod.startswith(("botocore", "boto3", "s3transfer")):
            return True
    except Exception:
        pass
    return False


def _has_runtime_object(v, _depth: int = 0) -> bool:
    """True if v IS, or (bounded-recursively) CONTAINS, a live runtime object
    (lock/pool/future/client). Used to keep such objects out of restore — a
    top-level executor OR a list/dict holding Futures both count."""
    if _is_live_runtime_object(v):
        return True
    if _depth >= 2:
        return False
    try:
        if isinstance(v, (list, tuple, set, frozenset)):
            return any(_has_runtime_object(e, _depth + 1) for e in list(v)[:64])
        if isinstance(v, dict):
            return any(_has_runtime_object(e, _depth + 1) for e in list(v.values())[:64])
    except Exception:
        pass
    return False


def _sanitize_restored_namespace(namespace: dict, live_namespace: dict | None = None):
    """Prepare a dill-restored namespace for adoption into the live executor.

    live_namespace: the executor namespace the restored functions are bound to
    (the notebook-namespace marker resolves to it). A value that IS it (a user's
    `g = globals()`) is kept as-is.

    DROPS live runtime objects (or containers holding them): a
    ThreadPoolExecutor / list of Futures / lock / boto3 client from the
    checkpointed process references dead threads; adopting one deadlocks the
    single-worker app (RUNNING but every request times out) and breaks
    re-serialization. So we remove it entirely.

    Every other value is adopted as unpickled, never copied: the by-name
    references (nspickle) restore objects shared between variables as one
    object (`b = a`, a dict held in another dict), and a copy per variable
    would split them again. (A per-variable deepcopy of list/dict/set values
    used to run here, from when the namespace was one pickle; it also raised
    the restore peak and re-pickled unchanged values to new bytes.)

    Mutates `namespace` in place AND returns (namespace, dropped) where `dropped`
    is a list of "name(Type)" strings for logging. Pure (no I/O, no executor) so it
    is unit-testable in isolation."""
    dropped = []
    for k, v in list(namespace.items()):
        if live_namespace is not None and v is live_namespace:
            continue
        if _has_runtime_object(v):
            dropped.append(f"{k}({type(v).__name__})")
            namespace.pop(k, None)
    return namespace, dropped


# Where the executor's display() shim is defined (module + qualname suffix).
_DISPLAY_SHIM_MODULE = "app.notebook.executor"
_DISPLAY_SHIM_QUALNAME_SUFFIX = "<locals>._display_fn"


def _is_display_shim(value) -> bool:
    """True for the executor's per-run display() shim (SandboxExecutor
    ._execute_locked.<locals>._display_fn), from ANY run, including a dill-restored
    copy from an older checkpoint. The shim is a closure over the executor, its
    event list and the run's stdout buffer: pickling it copies the whole
    executor (namespace included). A user's own `def display(...)` or
    `display = 5` does not match (different module / qualname). Never raises."""
    try:
        import types as _types
        return (isinstance(value, _types.FunctionType)
                and getattr(value, "__module__", None) == _DISPLAY_SHIM_MODULE
                and getattr(value, "__qualname__", "").endswith(_DISPLAY_SHIM_QUALNAME_SUFFIX))
    except Exception:
        return False


def _is_injected_value(key, value, injected: dict | None) -> bool:
    """True when `key` holds an object the executor injected: the display()
    shim (see _is_display_shim) or `injected[key]` itself (identity). A user who
    rebinds an injected name (`display = 5`, `def read_athena(...)`) is not
    matched. Never raises."""
    if _is_display_shim(value):
        return True
    try:
        return bool(injected) and key in injected and value is injected[key]
    except Exception:
        return False


def _drop_injected_from_restored(namespace: dict, injected: dict | None) -> list:
    """Remove from a dill-restored namespace the entries an older image saved
    for injected names, so they never replace the live executor's own objects:
      • any display() shim (its closure is a deserialized COPY of the old
        executor);
      • a helper whose restored value is the live helper itself, or the same
        function by module + qualname (an older image's copy of it).
    A user value under an injected name (`display = 5`) is kept. Mutates
    `namespace` in place; returns the dropped names. Pure, never raises."""
    dropped = []
    for k, v in list(namespace.items()):
        drop = _is_display_shim(v)
        if not drop and injected and k in injected:
            live = injected[k]
            try:
                drop = v is live or (
                    getattr(v, "__module__", None) is not None
                    and getattr(v, "__module__", None) == getattr(live, "__module__", None)
                    and getattr(v, "__qualname__", None) == getattr(live, "__qualname__", None))
            except Exception:
                drop = False
        if drop:
            namespace.pop(k, None)
            dropped.append(k)
    return dropped


def _filter_namespace_for_save(namespace: dict, skip_display_objects: bool = True,
                               injected: dict | None = None):
    """Decide which namespace vars to checkpoint. Excludes, by reason:
      • dunder    — __x__ keys (interpreter internals)
      • injected  — the display() shim (any name bound to it) and every
                    `injected` {name: object} entry still bound to that object
                    (identity), see _is_injected_value
      • module    — imported modules (re-imported from the import ledger on restore)
      • io        — open file handles (pickling reopens+TRUNCATES the /tmp file)
      • runtime   — live locks/pools/futures/boto3 clients (deadlock on restore)
      • display   — matplotlib/PIL display objects (expensive, non-essential)

    injected: the executor's injected names → objects (its helpers and current
    display() shim); None = only the display-shim check.

    Returns (namespace_to_save, skipped) where skipped is
    {reason: ["name(Type)", ...]} ("injected" lists bare names). Pure (no I/O,
    no executor) so it is unit-testable in isolation and shared by the real
    save() path."""
    import types as _types
    import io as _io
    skipped = {"module": [], "io": [], "runtime": [], "display": [], "injected": []}
    to_save = {}
    for key, value in namespace.items():
        if key.startswith("__") and key.endswith("__"):
            continue
        if _is_injected_value(key, value, injected):
            skipped["injected"].append(key)
            continue
        if isinstance(value, _types.ModuleType):
            skipped["module"].append(key)
            continue
        # Use the RECURSIVE check so a container holding runtime objects is also
        # excluded — e.g. `futures = [executor.submit(...) ...]` is a LIST of
        # Futures (each with a lock), which a top-level check would miss. This is
        # exactly the var that poisoned the "Burst Demo" checkpoint.
        if _has_runtime_object(value):
            skipped["runtime"].append(f"{key}({type(value).__name__})")
            continue
        if isinstance(value, _io.IOBase):
            skipped["io"].append(f"{key}({type(value).__name__})")
            continue
        if skip_display_objects and _is_excluded_from_checkpoint(value):
            skipped["display"].append(f"{key}({type(value).__name__})")
            continue
        to_save[key] = value
    return to_save, skipped


def _is_excluded_from_checkpoint(value, _depth: int = 0) -> bool:
    """
    Check if a value should be excluded from checkpoint serialization.
    Returns True for transient display objects (matplotlib figures, PIL images, etc.)
    that are expensive to serialize and not essential for state continuity.

    Also recurses (bounded) into containers so nested display objects are caught —
    e.g. `fig, axes = plt.subplots(2, 2)` makes `axes` an object-dtype ndarray of
    Axes, and `axs = [fig.add_subplot(...) for ...]` makes a list of Axes. Neither
    is matplotlib-typed at the top level, so a shallow check would let them through.
    """
    type_name = type(value).__name__
    module = getattr(type(value), "__module__", "") or ""

    # Fast check: type name
    if type_name in _EXCLUDED_TYPE_NAMES:
        return True

    # Module-based check: anything from matplotlib.* or PIL.*
    if module.startswith(_EXCLUDED_MODULE_PREFIXES):
        return True

    # Bounded recursion into containers. Depth + element caps keep this cheap and
    # cycle-safe; we only need to spot a display object, so first hit wins.
    if _depth >= 2:
        return False
    _MAX_ELEMS = 64
    try:
        if type_name == "ndarray":
            # Only object-dtype arrays can hold Python objects like Axes; numeric
            # arrays can't, so skip them (avoids scanning large numeric arrays).
            if getattr(value, "dtype", None) is not None and value.dtype == object:
                for i, elem in enumerate(value.flat):
                    if i >= _MAX_ELEMS:
                        break
                    if _is_excluded_from_checkpoint(elem, _depth + 1):
                        return True
        elif isinstance(value, (list, tuple, set, frozenset)):
            for i, elem in enumerate(value):
                if i >= _MAX_ELEMS:
                    break
                if _is_excluded_from_checkpoint(elem, _depth + 1):
                    return True
        elif isinstance(value, dict):
            for i, elem in enumerate(value.values()):
                if i >= _MAX_ELEMS:
                    break
                if _is_excluded_from_checkpoint(elem, _depth + 1):
                    return True
    except Exception:
        # Never let the exclusion probe crash a checkpoint save.
        pass

    return False
