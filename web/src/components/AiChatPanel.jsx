// Rendered-preview HTML for ```markdown cards, memoized on the raw source string.
// Uses the SAME shared renderer as notebook markdown cells (services/markdown.js:
// GFM tables, KaTeX, mermaid placeholders). The output is NOT trusted here — it is
// embedded in the message HTML, which AssistantMarkdown runs through
// sanitizeMarkdown (then spliceCachedMermaid) as a whole. The cache matters because
// the whole message is re-parsed on every streamed token; finished cards then cost
// a Map lookup. renderMarkdown never throws (falls back to escaped <pre>), so a
// half-streamed table/fence just renders as partial markdown.
const _mdPreviewCache = new Map()
const MD_PREVIEW_CACHE_MAX = 200
function renderMarkdownPreview(text) {
  const key = text || ''
  let html = _mdPreviewCache.get(key)
  if (html === undefined) {
    html = renderMarkdown(key)
    if (_mdPreviewCache.size >= MD_PREVIEW_CACHE_MAX) {
      _mdPreviewCache.delete(_mdPreviewCache.keys().next().value)  // evict oldest
    }
    _mdPreviewCache.set(key, html)
  }
  return html
}

