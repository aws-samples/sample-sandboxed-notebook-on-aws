// Show / remove a tracked card's "Inserted" marker + "Jump to cell" link. The card
// HTML is regenerated by marked whenever its message changes, so this is re-applied
// on every commit (idempotent). A cell that exists but isn't rendered right now
// (e.g. App view) gets a disabled link with a tooltip.
function applyInsertedMarker(block, cellId) {
  const actions = block.querySelector('.ai-code-actions')
  if (!actions) return
  let mark = actions.querySelector('.ai-code-inserted-mark')
  let jump = actions.querySelector('.ai-code-jump-btn')
  if (!cellId) {
    block.classList.remove('ai-code-inserted')
    mark?.remove()
    jump?.remove()
    return
  }
  block.classList.add('ai-code-inserted')
  if (!mark) {
    mark = document.createElement('span')
    mark.className = 'ai-code-inserted-mark'
    mark.textContent = '✓ Inserted'
    actions.prepend(mark)
  }
  if (!jump) {
    jump = document.createElement('button')
    jump.type = 'button'
    jump.className = 'ai-code-jump-btn'
    jump.textContent = 'Jump to cell'
    mark.after(jump)
  }
  if (jump.getAttribute('data-cell-id') !== cellId) jump.setAttribute('data-cell-id', cellId)
  const inDom = isCellInDom(cellId)
  const disabled = inDom ? 'false' : 'true'
  if (jump.getAttribute('aria-disabled') !== disabled) jump.setAttribute('aria-disabled', disabled)
  const title = inDom ? 'Scroll the notebook to the inserted cell' : 'Cell not visible in the Notebook view'
  if (jump.title !== title) jump.title = title
}

const renderer = new marked.Renderer()
renderer.code = function({ text, lang }) {
  // ```mermaid → a placeholder div; AssistantMarkdown renders + splices in the SVG
  // (ensureMermaidRendered + spliceCachedMermaid), same pipeline as shared <Markdown>.
  const lk = langKey(lang)
  if (lk === 'mermaid') {
    const encoded = encodeURIComponent(text || '')
    const esc = String(text || '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    return `<div class="mermaid-diagram" data-mermaid="${encoded}"><pre class="mermaid-src">${esc}</pre></div>`
  }
  // Insertable fences (python/py/sql/markdown/bare) are tracked per turn (Inserted
  // marker, counts, Insert all); other fences (bash, json, …) keep a plain Insert.
  const insType = insertableType(lang)
  const cellType = insType || 'code'
  const tracked = insType && String(text || '').trim() ? ' data-insertable="1"' : ''
  const label = CODE_LANG_LABEL[cellType] || 'Code'
  // Render each fenced block as a CODE CARD: a header strip (language label +
  // Copy/Insert actions) above a monospaced code body.
  //
  // Body HTML: all three types run a self-contained single-pass tokenizer that
  // escapes as it emits and consumes every char exactly once, so it CANNOT
  // duplicate content (the old Lezer highlighter did, when its output was fed
  // back through marked). python/sql → highlightBasic; markdown → highlightMarkdown
  // (light source tinting, NOT a marked re-render). Either way the <code>'s
  // textContent stays the raw code, so Copy/Insert (which read textContent) are
  // unaffected.
  const isMd = cellType === 'markdown'
  const body = isMd
    ? highlightMarkdown(text)
    : highlightBasic(text, cellType === 'sql' ? 'sql' : 'python')
  // Markdown cards additionally carry a RENDERED preview (shown by default) plus a
  // Source/Preview toggle; the raw-source <pre> stays in the DOM (hidden via CSS)
  // so Copy/Insert keep reading the raw markdown from `.ai-code-pre > code`.
  const viewBtn = isMd
    ? `<button class="ai-code-view-btn" title="Show markdown source">Source</button>`
    : ''
  const preview = isMd
    ? `<div class="ai-md-preview md-rendered">${renderMarkdownPreview(text)}</div>`
    : ''
  return (
    `<div class="ai-code-block" data-lang="${cellType}"${tracked}>` +
      `<div class="ai-code-head">` +
        `<button class="ai-code-toggle" title="Collapse / expand" aria-label="Collapse or expand code">▾</button>` +
        `<span class="ai-code-lang">${label}</span>` +
        `<div class="ai-code-actions">` +
          viewBtn +
          `<button class="ai-code-copy-btn">Copy</button>` +
          `<button class="ai-code-insert-btn">Insert</button>` +
        `</div>` +
      `</div>` +
      preview +
      `<pre class="ai-code-pre"><code class="language-${lk.replace(/[^a-z0-9_+-]/g, '')}">${body}</code></pre>` +
    `</div>`
  )
}
