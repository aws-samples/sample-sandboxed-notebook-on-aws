// A tiny emoji icon for an attachment chip, chosen from mime/extension.
function attachIcon(mime, name) {
  const m = (mime || '').toLowerCase()
  const ext = (name || '').includes('.') ? name.split('.').pop().toLowerCase() : ''
  if (m.startsWith('image/') || ['png', 'jpg', 'jpeg', 'gif', 'webp'].includes(ext)) return '🖼️'
  if (m === 'application/pdf' || ext === 'pdf') return '📕'
  if (m === 'application/json' || ext === 'json') return '🧾'
  if (['csv', 'xls', 'xlsx'].includes(ext) || m.includes('excel') || m.includes('spreadsheet')) return '📊'
  if (['doc', 'docx'].includes(ext) || m.includes('word')) return '📄'
  return '📎'
}

/**
 * Context-aware starter prompts for the empty chat state. Derived entirely from
 * signals already on the tab (cells, variables, data sources) — no extra fetch.
 * Returns up to `max` short {label, prompt} chips; the highest-signal suggestions
 * (errors, your actual DataFrames/tables) come first, with generic fallbacks so
 * there's always something useful to click.
 */
function computeSuggestions(activeTab, max = 4) {
  if (!activeTab) return []
  const cells = activeTab._cells || []
  const variables = activeTab._variables || {}
  const ds = activeTab._dataSources || {}
  const out = []
  const seen = new Set()
  const add = (label, prompt) => {
    if (out.length >= max || seen.has(label)) return
    seen.add(label)
    out.push({ label, prompt })
  }

  // 1. Errors are the most actionable — offer to fix the first one. Reference the
  // cell by its user-visible badge (PY-4 / SQL-2) so it matches what's on screen.
  const errIdx = cells.findIndex(c => c.error)
  if (errIdx >= 0) {
    const badge = cellBadgeList(cells)[errIdx]
    add('Fix the error', `Fix the error in cell ${badge}.`)
  }

  // 2. A real DataFrame in the namespace → offer to visualize/summarize it.
  const dfName = Object.entries(variables)
    .find(([, info]) => info && (info.type === 'DataFrame' || info.type === 'Series'))?.[0]
  if (dfName) {
    add(`Plot ${dfName}`, `Create a clear visualization of ${dfName} and briefly explain what it shows.`)
    add(`Summarize ${dfName}`, `Give me summary statistics and key insights for ${dfName}.`)
  }

  // 3. A connected data source → offer to query it (prefer Athena, then DynamoDB, then S3).
  const athena = (ds.athena || [])[0]
  const dynamo = (ds.dynamodb || [])[0]
  const s3 = (ds.s3 || [])[0]
  if (athena?.name) {
    const ref = athena.database ? `${athena.database}.${athena.name}` : athena.name
    add(`Explore ${athena.name}`, `Query the ${ref} table and show me a few rows with a short summary.`)
  } else if (dynamo?.name) {
    add(`Explore ${dynamo.name}`, `Query the DynamoDB table ${dynamo.name} and summarize what's in it.`)
  } else if (s3) {
    const uri = s3.uri || (s3.bucket && s3.key ? `s3://${s3.bucket}/${s3.key}` : null)
    if (uri) add('Explore my S3 data', `Load ${uri} into a DataFrame and describe it.`)
  }

  // 4. Generic, always-useful fallbacks.
  if (cells.some(c => (c.code || '').trim())) {
    add('Explain this notebook', 'Explain what this notebook does, step by step.')
  }
  add('Analyze a sample dataset', 'Load an interesting sample dataset and do a quick exploratory analysis with a chart.')
  add('What can you do?', 'What can you help me with in this notebook?')

  return out.slice(0, max)
}

// Assistant markdown, memoized on the raw content string. marked.parse +
// dangerouslySetInnerHTML rebuilds the whole message DOM on every render; the
// panel re-renders on unrelated 10s polls (workbook-intel, session costs, VM
// instances), so without this the message HTML was torn down and re-laid-out
// every few seconds — a visible flicker. React.memo keeps the parsed HTML stable
// unless the message text actually changes (e.g. tokens streaming in).
const AssistantMarkdown = memo(function AssistantMarkdown({ content }) {
  const [tick, setTick] = useState(0)
  // Chat uses its own `marked` (code cards + normalizeFences), but its mermaid
  // fences emit the same placeholder as the shared renderer, so spliceCachedMermaid
  // splices in cached SVGs here too. `tick` MUST be a dep so this re-runs when a
  // diagram finishes rendering and the SVG lands in the HTML string React owns
  // (survives streaming re-renders instead of being wiped by an imperative inject).
  const html = useMemo(
    // Splice mermaid SVGs AFTER sanitize (DOMPurify strips foreignObject labels).
    () => spliceCachedMermaid(sanitizeMarkdown(marked.parse(normalizeFences(content), { breaks: true }))),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [content, tick]
  )
  useEffect(() => {
    let cancelled = false
    const raw = marked.parse(normalizeFences(content), { breaks: true })
    ensureMermaidRendered(raw).then((changed) => {
      if (changed && !cancelled) setTick((t) => t + 1)
    })
    return () => { cancelled = true }
  }, [content, tick])
  // Re-theme live on an app theme toggle: the shared observer cleared the mermaid
  // cache, so bumping tick re-renders the SVGs here under the new theme too.
  useEffect(() => onMermaidThemeChange(() => setTick((t) => t + 1)), [])
  return <div className="ai-msg-md" dangerouslySetInnerHTML={{ __html: html }} />
})

